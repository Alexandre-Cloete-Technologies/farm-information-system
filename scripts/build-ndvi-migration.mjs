/**
 * Turns fetched DynaCrop NDVI into a versioned migration.
 *
 *   node scripts/build-ndvi-migration.mjs <fetched.json> <out.sql>
 *
 * Kept as SQL rather than a runtime loader so the database stays reproducible
 * from migrations alone, with no manual dashboard steps.
 *
 * Two filters matter:
 *  - DynaCrop masks cloud, shadow and built-up pixels with -999. Those must
 *    never reach the database as if they were measurements.
 *  - NDVI is mathematically bounded to [-1, 1]; anything outside is bad data.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const CLOUD_MASK = -999;

/** Median NDVI for a date, or null if the observation is unusable. */
export function usableNdvi(stats) {
  const v = stats?.median;
  if (v === null || v === undefined || Number.isNaN(v)) return null;
  if (v <= CLOUD_MASK + 1) return null; // cloud/shadow/built-up mask
  if (v < -1 || v > 1) return null; // outside the index's valid range
  return Math.round(v * 10000) / 10000;
}

/** Build the migration text. Exported so tests can exercise it without file IO. */
export function buildMigration(source) {
const stats = {};
const blocks = [];
let total = 0;

for (const [zone, { observations }] of Object.entries(source.zones)) {
  const dates = [];
  const values = [];
  let dropped = 0;

  for (const [date, raw] of Object.entries(observations).sort()) {
    const value = usableNdvi(raw);
    if (value === null) {
      dropped++;
      continue;
    }
    dates.push(date);
    values.push(value);
  }

  stats[zone] = { kept: dates.length, dropped };
  total += dates.length;

  // Parallel arrays rather than one tuple per row: same data, a third the size.
  blocks.push(`-- ${zone}: ${dates.length} observations
insert into public.mock_readings
  (farm_id, zone_id, vendor_label, metric_type, value, unit,
   recorded_at, observed_on, origin, source_platform, source_product)
select z.farm_id, z.id, 'DynaCrop · Sentinel-2', 'ndvi', obs.value, 'index',
       obs.observed_on + time '10:15', obs.observed_on,
       'satellite', 'Sentinel-2', 'NDVI'
from public.farm_zones z,
     unnest(
       array[${dates.map((d) => `'${d}'`).join(",")}]::date[],
       array[${values.join(",")}]::double precision[]
     ) as obs(observed_on, value)
where z.name = '${zone.replace(/'/g, "''")}'
on conflict do nothing;`);
}

const sql = `-- Real Sentinel-2 NDVI for the three registered management zones.
--
-- Source: DynaCrop (World from Space), polygons registered from our own survey
-- geometry. Values are the per-zone median for each satellite acquisition,
-- ${source.dateFrom} to ${source.dateTo}, fetched ${source.fetchedAt.slice(0, 10)}.
--
-- Generated by scripts/build-ndvi-migration.mjs from the output of
-- scripts/fetch-dynacrop-ndvi.mjs. Cloud-masked (-999) and out-of-range
-- observations are already excluded.
--
-- Kept per zone: ${Object.entries(stats)
  .map(([z, s]) => `${z} ${s.kept} (${s.dropped} masked)`)
  .join(", ")}
--
-- North Grazing Camp is deliberately absent: the trial plan allows three
-- registered fields and the farm has four zones. It stays simulated, which is
-- what the real-vs-simulated marking in the UI exists to show.

-- Replace any simulated NDVI for these zones so a chart never mixes measured
-- and modelled values in one line.
delete from public.mock_readings r
using public.farm_zones z
where r.zone_id = z.id
  and r.metric_type = 'ndvi'
  and r.origin = 'simulated'
  and z.name in (${Object.keys(source.zones).map((z) => `'${z.replace(/'/g, "''")}'`).join(", ")});

${blocks.join("\n\n")}
`;

  return { sql, stats, total };
}

// CLI entry point. Guarded so importing this module for its pure helpers does
// not try to read argv and write files.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [, , inFile, outFile] = process.argv;
  if (!inFile || !outFile) throw new Error("usage: build-ndvi-migration.mjs <in.json> <out.sql>");

  const { sql, stats, total } = buildMigration(JSON.parse(readFileSync(inFile, "utf8")));
  writeFileSync(outFile, sql);

  console.error(`wrote ${outFile}`);
  for (const [z, s] of Object.entries(stats)) {
    console.error(`  ${z.padEnd(20)} ${s.kept} kept, ${s.dropped} masked`);
  }
  console.error(`  total rows: ${total}`);
}
