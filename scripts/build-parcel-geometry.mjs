/**
 * Regenerates the demo farm's geometry from OpenStreetMap.
 *
 *   node scripts/build-parcel-geometry.mjs [osmWayId]
 *
 * Prints a SQL migration to stdout. Run it, review the areas, then save the
 * output as a new file in supabase/migrations/.
 *
 * Why this exists: the first version of the demo farm was a rectangle drawn to
 * match a listing's hectares, and it looked obviously synthetic sitting on a
 * satellite basemap. This pulls a real surveyed parcel instead, and subdivides
 * it into management zones that follow the outline rather than a grid.
 */
import { writeFileSync } from "node:fs";

const WAY_ID = Number(process.argv[2] ?? 701878889);
/** Search centre: Brakwater, ~20 km north of Windhoek. */
const SEARCH = { lat: -22.44, lon: 17.075, radiusM: 25000 };

const OVERPASS_QUERY = `
[out:json][timeout:90];
(
  way["landuse"~"^(farmland|farmyard|orchard|vineyard)$"](around:${SEARCH.radiusM},${SEARCH.lat},${SEARCH.lon});
  way["place"="farm"](around:${SEARCH.radiusM},${SEARCH.lat},${SEARCH.lon});
);
out geom;
`;

/** Spherical polygon area in hectares. Used for both parcel and zones so they reconcile. */
function areaHa(ring) {
  const R = 6378137;
  const closed = ring[0] === ring.at(-1) ? ring : [...ring, ring[0]];
  let sum = 0;
  for (let i = 0; i < closed.length - 1; i++) {
    const [lon1, lat1] = closed[i];
    const [lon2, lat2] = closed[i + 1];
    sum +=
      (((lon2 - lon1) * Math.PI) / 180) *
      (2 + Math.sin((lat1 * Math.PI) / 180) + Math.sin((lat2 * Math.PI) / 180));
  }
  return Math.abs((sum * R * R) / 2) / 10_000;
}

/** Sutherland-Hodgman clip against the half-plane a*x + b*y <= c. */
function clipHalfPlane(poly, a, b, c) {
  const out = [];
  const inside = (p) => a * p[0] + b * p[1] <= c + 1e-9;
  for (let i = 0; i < poly.length; i++) {
    const cur = poly[i];
    const prev = poly[(i - 1 + poly.length) % poly.length];
    if (inside(cur) !== inside(prev)) {
      const dx = cur[0] - prev[0];
      const dy = cur[1] - prev[1];
      const denom = a * dx + b * dy;
      if (Math.abs(denom) > 1e-12) {
        const t = (c - (a * prev[0] + b * prev[1])) / denom;
        out.push([prev[0] + t * dx, prev[1] + t * dy]);
      }
    }
    if (inside(cur)) out.push(cur);
  }
  return out;
}

const res = await fetch("https://overpass-api.de/api/interpreter", {
  method: "POST",
  headers: {
    "Content-Type": "application/x-www-form-urlencoded",
    // Overpass returns 406 without one.
    "User-Agent": "FIS-MVP/0.1 (farm information system prototype)",
  },
  body: "data=" + encodeURIComponent(OVERPASS_QUERY),
});
if (!res.ok) throw new Error(`Overpass ${res.status}: ${await res.text()}`);

const el = (await res.json()).elements.find((e) => e.id === WAY_ID);
if (!el?.geometry) throw new Error(`way ${WAY_ID} not found in the search area`);

const ring = el.geometry.map((p) => [+p.lon.toFixed(6), +p.lat.toFixed(6)]);
if (String(ring[0]) !== String(ring.at(-1))) ring.push(ring[0]);
const parcelHa = Math.round(areaHa(ring) * 100) / 100;

const lons = ring.map((r) => r[0]);
const lats = ring.map((r) => r[1]);
const ORIGIN = [(Math.min(...lons) + Math.max(...lons)) / 2, (Math.min(...lats) + Math.max(...lats)) / 2];
const M_PER_LAT = 110900;
const M_PER_LON = 111320 * Math.cos((ORIGIN[1] * Math.PI) / 180);
const toM = ([lon, lat]) => [(lon - ORIGIN[0]) * M_PER_LON, (lat - ORIGIN[1]) * M_PER_LAT];
const toLL = ([x, y]) => [
  +(ORIGIN[0] + x / M_PER_LON).toFixed(6),
  +(ORIGIN[1] + y / M_PER_LAT).toFixed(6),
];

// Seed positions in metres from the parcel centre. Asymmetric on purpose: the
// cropland block sits north near the homestead notch, the riverbed strip
// follows the low ground in the south-west.
const SEEDS = [
  { name: "Maize Block", at: [30, 215] },
  { name: "North Grazing Camp", at: [-70, 40] },
  { name: "South Grazing Camp", at: [95, -130] },
  { name: "Riverbed Strip", at: [-135, -225] },
];

const ringM = ring.slice(0, -1).map(toM);
const zones = SEEDS.map((seed, i) => {
  let cell = ringM;
  const [px, py] = seed.at;
  for (let j = 0; j < SEEDS.length; j++) {
    if (j === i) continue;
    const [qx, qy] = SEEDS[j].at;
    // Points nearer p than q: 2(q-p)·x <= |q|^2 - |p|^2
    cell = clipHalfPlane(cell, 2 * (qx - px), 2 * (qy - py), qx * qx + qy * qy - px * px - py * py);
  }
  const cellLL = cell.map(toLL);
  return { name: seed.name, ha: Math.round(areaHa(cellLL) * 100) / 100, ring: [...cellLL, cellLL[0]] };
});

const poly = (r) => `'${JSON.stringify({ type: "Polygon", coordinates: [r] })}'::jsonb`;
const sql = `-- Generated by scripts/build-parcel-geometry.mjs (OSM way ${WAY_ID}).
-- Parcel ${parcelHa} ha, ${ring.length - 1} vertices. Zones are a Voronoi
-- subdivision of the boundary, not survey data.

update public.farms
set area_ha          = ${parcelHa},
    centroid_lon     = ${ORIGIN[0].toFixed(6)},
    centroid_lat     = ${ORIGIN[1].toFixed(6)},
    boundary_geojson = ${poly(ring)};

${zones
  .map(
    (z) => `update public.farm_zones
set area_ha = ${z.ha}, geojson = ${poly(z.ring)}
where name = '${z.name.replace(/'/g, "''")}';`,
  )
  .join("\n\n")}
`;

const total = Math.round(zones.reduce((t, z) => t + z.ha, 0) * 100) / 100;
console.error(`parcel ${parcelHa} ha (${ring.length - 1} vertices) -> zones total ${total} ha`);
for (const z of zones) console.error(`  ${z.name.padEnd(20)} ${String(z.ha).padStart(6)} ha`);

const out = process.env.TEMP ? `${process.env.TEMP}/parcel.sql` : "parcel.sql";
writeFileSync(out, sql);
console.error(`\nwrote ${out}`);
process.stdout.write(sql);
